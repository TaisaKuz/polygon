import numpy as np
import pygame

# Устаенавливаем размеры поля
WIDTH, HEIGHT = 20, 10  # Количество клеток
CELL_SIZE = 30  # Размер клетки в пикселях
FPS = 5  # Частота обновлений в кадрах

# Подбираем цвета
BACKGROUND_COLOR = (0, 0, 0)  # Черный фон для мертвых клеток
CELL_COLOR = (0, 255, 0)  # Зеленый цвет для живых клеток
GRID_COLOR = (50, 50, 50)  # Серый цвет для рисования сетки

# Инициализация библиотеки pygame
pygame.init()

# Окно для игры с размерами, пропорциональными количеству клеток и размеру каждой клетки
screen = pygame.display.set_mode((WIDTH * CELL_SIZE, HEIGHT * CELL_SIZE))
pygame.display.set_caption("Игра жизнь")  # Устанавливаем заголовок окна


# Функция для обновления состояния матрицы
def update_matrix(matrix):
    """
    Обновляем состояния игрового поля по правилам "Игры жизни".
    Мы создаем новую матрицу, чтобы избежать конфликтов данных
    при обновлении состояния клеток.
    """
    new_matrix = np.zeros_like(matrix)  # Создаем пустую матрицу с теми же размерами, что и исходная

    # Проходим по всем клеткам игрового поля
    for y in range(HEIGHT):
        for x in range(WIDTH):
            # Считаем количество живых соседей для клетки (x, y)
            # Используем индексацию с учетом цикличности (края поля связываются)
            neighbors = np.sum(matrix[(y - 1):(y + 2) % HEIGHT, (x - 1):(x + 2) % WIDTH]) - matrix[y, x]

            # Применяем правила "Игры жизни"
            if matrix[y, x] == 1:  # Клетка живая
                if neighbors < 2 or neighbors > 3:  # Смерть от одиночества или перенаселенности
                    new_matrix[y, x] = 0  # Клетка умирает
                else:
                    new_matrix[y, x] = 1  # Клетка остается живой
            else:  # Клетка мертвая
                if neighbors == 3:  # Если 3 соседа, клетка оживает
                    new_matrix[y, x] = 1  # Клетка становится живой
    return new_matrix


# Функция для отрисовки матрицы на экране с сеткой
def draw_matrix(matrix):
    """
    Отрисовывает игровое поле на экране, а также рисует сетку между клетками.
    Мы проходим по всем клеткам и рисуем их на экране, используя цвет для каждой клетки.
    """
    for y in range(HEIGHT):
        for x in range(WIDTH):
            # Определяем цвет клетки в зависимости от ее состояния (живая или мертвая)
            color = CELL_COLOR if matrix[y, x] == 1 else BACKGROUND_COLOR
            # Рисуем прямоугольник для клетки (параметры: цвет, положение, размер)
            pygame.draw.rect(screen, color, (x * CELL_SIZE, y * CELL_SIZE, CELL_SIZE, CELL_SIZE))

            # Рисуем сетку между клетками (границу клеток), для улучшения видимости
            pygame.draw.rect(screen, GRID_COLOR, (x * CELL_SIZE, y * CELL_SIZE, CELL_SIZE, CELL_SIZE), 1)


# Функция для запуска игры
def run_game():
    """
    Запускает игру, инициализирует начальное состояние и обновляет поле в цикле.
    В цикле происходит отрисовка матрицы и обновление ее состояния по правилам игры.
    """
    # Инициализируем случайное начальное состояние (матрица с 0 и 1)
    # Используем np.random.choice для случайного выбора 0 или 1 в каждой клетке
    matrix = np.random.choice([0, 1], size=(HEIGHT, WIDTH))

    # Основной цикл игры
    running = True  # Флаг для управления циклом игры
    clock = pygame.time.Clock()  # Объект для управления частотой кадров (FPS)

    while running:
        # Обрабатываем все события (закрытие окна)
        for event in pygame.event.get():
            if event.type == pygame.QUIT:  # Если пользователь закрыл окно
                running = False  # Прерываем игровой цикл

        # Очищаем экран перед тем, как нарисовать новый кадр
        screen.fill(BACKGROUND_COLOR)

        # Отображаем матрицу на экране
        draw_matrix(matrix)

        # Обновляем состояние матрицы по правилам игры
        matrix = update_matrix(matrix)

        # Обновляем экран, чтобы отобразить изменения
        pygame.display.flip()

        # Ограничиваем количество кадров в секунду (FPS), чтобы контролировать скорость игры
        clock.tick(FPS)

    # Завершаем работу с pygame при выходе из игры
    pygame.quit()

        # Запуск игры
if __name__ == "__main__":
    run_game()